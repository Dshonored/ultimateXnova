require_once 'includes/classes/Mail.class.php';
require_once 'includes/classes/LoginThrottle.class.php';

/**
 * Password recovery by e-mail.
 *
 * Flow: the player enters their e-mail -> we mail a single-use link (valid 30 min) ->
 * the link opens a form where they choose a new password. The new password is never
 * generated by us and never sent by e-mail.
 *
 * Security notes (rewritten for friends-edition):
 * - the old flow redirected straight to the reset link when no mail server was set up
 *   and then printed the new password on screen (account takeover with username + mail)
 * - tokens are 256-bit random; only a hash is stored
 * - links use APP_URL instead of the Host header (no reset-link poisoning)
 * - the response is identical whether the e-mail exists or not (no account enumeration)
 * - a successful reset kills every session and remember-me token of the account
 */
class ShowLostPasswordPage extends AbstractLoginPage
{
	public static $requireModule = 0;

	const TOKEN_TTL       = 1800;  // 30 minutes
	const RESEND_COOLDOWN = 900;   // one mail per account every 15 minutes
	const MIN_PASSWORD    = 8;

	function __construct()
	{
		parent::__construct();
	}

	function show()
	{
		$this->assign(array(
			'csrfToken'   => $this->generateCSRFToken(),
			'mailEnabled' => Mail::isConfigured(),
		));
		$this->display('page.lostPassword.default.tpl');
	}

	function send()
	{
		global $LNG;

		$this->requireCsrf('index.php?page=lostPassword');

		$mail = trim(HTTP::_GP('mail', '', true));

		if (!Mail::isConfigured()) {
			$this->printMessage($LNG['passwordMailNotConfigured'], $this->backButton());
		}

		if ($mail === '' || filter_var($mail, FILTER_VALIDATE_EMAIL) === false) {
			$this->printMessage($LNG['passwordErrorMailEmpty'], $this->backButton());
		}

		if (LoginThrottle::isBlocked('reset:'.$mail)) {
			$this->printMessage($LNG['login_error_throttled'], $this->backButton());
		}
		LoginThrottle::recordFailure('reset:'.$mail);

		$db = Database::get();

		$sql = "SELECT id, username, email, universe FROM %%USERS%% WHERE universe = :universe AND email = :mail;";
		$user = $db->selectSingle($sql, array(
			':universe' => Universe::current(),
			':mail'     => $mail,
		));

		if (!empty($user)) {
			$sql = "SELECT COUNT(*) as state FROM %%LOSTPASSWORD%% WHERE userID = :userID AND time > :time AND hasChanged = 0;";
			$recent = $db->selectSingle($sql, array(
				':userID' => $user['id'],
				':time'   => TIMESTAMP - self::RESEND_COOLDOWN,
			), 'state');

			if (empty($recent)) {
				$token = bin2hex(random_bytes(32));

				$sql = "INSERT INTO %%LOSTPASSWORD%% SET userID = :userID, `key` = :key, `time` = :timestamp, fromIP = :remoteAddr;";
				$db->insert($sql, array(
					':userID'     => $user['id'],
					':key'        => self::hashToken($token),
					':timestamp'  => TIMESTAMP,
					':remoteAddr' => Session::getClientIp(),
				));

				$config = Config::get($user['universe']);
				$link = Mail::appUrl().'index.php?page=lostPassword&mode=reset&u='.(int) $user['id'].'&k='.$token;

				$content = str_replace(
					array('{USERNAME}', '{GAMENAME}', '{VALIDURL}'),
					array($user['username'], $config->game_name, $link),
					$LNG->getTemplate('email_lost_password_validation')
				);

				Mail::send($user['email'], $user['username'], sprintf($LNG['passwordValidMailTitle'], $config->game_name), $content);
			}
		}

		// Same answer whether or not the address belongs to an account
		$this->printMessage($LNG['passwordValidMailSend'], array(array(
			'label' => $LNG['passwordNext'],
			'url'   => 'index.php',
		)));
	}

	/**
	 * GET: show the "choose a new password" form. POST: apply it.
	 */
	function reset()
	{
		global $LNG;

		$userID = (int) HTTP::_GP('u', 0);
		$token  = HTTP::_GP('k', '');

		if (!$this->isValidToken($userID, $token)) {
			$this->printMessage($LNG['passwordValidInValid'], $this->backButton());
		}

		if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
			$this->assign(array(
				'csrfToken'   => $this->generateCSRFToken(),
				'resetUser'   => $userID,
				'resetToken'  => $token,
				'minPassword' => self::MIN_PASSWORD,
			));
			$this->display('page.lostPassword.reset.tpl');
		}

		$this->requireCsrf('index.php?page=lostPassword&mode=reset&u='.$userID.'&k='.urlencode($token));

		$password = HTTP::_GP('password', '', true);
		$confirm  = HTTP::_GP('passwordReplay', '', true);
		$retry    = array(array(
			'label' => $LNG['passwordBack'],
			'url'   => 'index.php?page=lostPassword&mode=reset&u='.$userID.'&k='.urlencode($token),
		));

		if (mb_strlen($password) < self::MIN_PASSWORD) {
			$this->printMessage(sprintf($LNG['registerErrorPasswordLength'], self::MIN_PASSWORD), $retry);
		}
		if (!hash_equals($password, $confirm)) {
			$this->printMessage($LNG['registerErrorPasswordSame'], $retry);
		}

		$db = Database::get();

		$db->update("UPDATE %%USERS%% SET password = :password WHERE id = :userID;", array(
			':password' => PlayerUtil::cryptPassword($password),
			':userID'   => $userID,
		));
		// Burn every pending link and every way back into the account
		$db->update("UPDATE %%LOSTPASSWORD%% SET hasChanged = 1 WHERE userID = :userID;", array(':userID' => $userID));
		$db->delete("DELETE FROM %%REMEMBER_ME%% WHERE user_id = :userID;", array(':userID' => $userID));
		$db->delete("DELETE FROM %%SESSION%% WHERE userID = :userID;", array(':userID' => $userID));

		$user = $db->selectSingle("SELECT username, email, universe FROM %%USERS%% WHERE id = :userID;", array(':userID' => $userID));
		if (!empty($user)) {
			$config  = Config::get($user['universe']);
			$content = str_replace(
				array('{USERNAME}', '{GAMENAME}'),
				array($user['username'], $config->game_name),
				$LNG->getTemplate('email_lost_password_changed')
			);
			Mail::send($user['email'], $user['username'], sprintf($LNG['passwordChangedMailTitle'], $config->game_name), $content);
		}

		$this->printMessage($LNG['passwordChangedDone'], array(array(
			'label' => $LNG['passwordNext'],
			'url'   => 'index.php',
		)));
	}

	/** Old e-mails pointed to mode=newPassword. */
	function newPassword()
	{
		$this->reset();
	}

	private function isValidToken($userID, $token)
	{
		if ($userID <= 0 || !is_string($token) || !preg_match('/^[a-f0-9]{64}$/', $token)) {
			return false;
		}

		$sql = "SELECT COUNT(*) as state FROM %%LOSTPASSWORD%% WHERE userID = :userID AND `key` = :key AND `time` > :time AND hasChanged = 0;";
		return (bool) Database::get()->selectSingle($sql, array(
			':userID' => $userID,
			':key'    => self::hashToken($token),
			':time'   => TIMESTAMP - self::TOKEN_TTL,
		), 'state');
	}

	private function requireCsrf($backUrl)
	{
		global $LNG;
		$posted = HTTP::_GP('csrfToken', '', true);
		if ($posted === '' || !isset($_COOKIE['csrfToken']) || !hash_equals((string) $_COOKIE['csrfToken'], $posted)) {
			$this->printMessage($LNG['passwordErrorExpired'], array(array(
				'label' => $LNG['passwordBack'],
				'url'   => $backUrl,
			)));
		}
	}

	private function backButton()
	{
		global $LNG;
		return array(array(
			'label' => $LNG['passwordBack'],
			'url'   => 'index.php?page=lostPassword',
		));
	}

	/** The `key` column is varchar(32): store 128 bits of the SHA-256 of the 256-bit token. */
	private static function hashToken($token)
	{
		return substr(hash('sha256', $token), 0, 32);
	}

}
